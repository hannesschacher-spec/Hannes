CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  pass_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','mitarbeit','lesen') NOT NULL DEFAULT 'mitarbeit',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL,
  last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS login_attempts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ip VARCHAR(45) NOT NULL,
  email VARCHAR(190) NOT NULL,
  ts DATETIME NOT NULL,
  INDEX (ip), INDEX (email), INDEX (ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS haeuser (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL,
  farbe VARCHAR(20) NOT NULL DEFAULT 'grau',
  kontakt VARCHAR(80) NOT NULL DEFAULT '',
  telefon VARCHAR(40) NOT NULL DEFAULT '',
  updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS platzarten (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  haus_id INT UNSIGNED NOT NULL,
  art VARCHAR(60) NOT NULL,
  frei INT UNSIGNED NOT NULL DEFAULT 0,
  gesamt INT UNSIGNED NULL,
  ab DATE NULL,
  hinweis VARCHAR(160) NOT NULL DEFAULT '',
  FOREIGN KEY (haus_id) REFERENCES haeuser(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS anfragen (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  haus_id INT UNSIGNED NULL,
  aufgenommen_von VARCHAR(80) NOT NULL DEFAULT '',
  anrufer VARCHAR(100) NOT NULL,
  telefon VARCHAR(40) NOT NULL DEFAULT '',
  fuer VARCHAR(60) NOT NULL DEFAULT '',
  ab DATE NULL,
  art VARCHAR(60) NOT NULL DEFAULT '',
  notiz TEXT NULL,
  status ENUM('offen','rueckruf','angeboten','zugesagt','abgeschlossen') NOT NULL DEFAULT 'offen',
  angebot_haus_id INT UNSIGNED NULL,
  angebot_platz_id INT UNSIGNED NULL,
  platz_vergeben TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  INDEX (status), INDEX (updated_at),
  FOREIGN KEY (haus_id) REFERENCES haeuser(id) ON DELETE SET NULL,
  FOREIGN KEY (angebot_haus_id) REFERENCES haeuser(id) ON DELETE SET NULL,
  FOREIGN KEY (angebot_platz_id) REFERENCES platzarten(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS verlauf (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  anfrage_id INT UNSIGNED NOT NULL,
  user_name VARCHAR(80) NOT NULL DEFAULT '',
  text VARCHAR(400) NOT NULL,
  created_at DATETIME NOT NULL,
  FOREIGN KEY (anfrage_id) REFERENCES anfragen(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
